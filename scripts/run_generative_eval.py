"""Run the generative eval: same 50-question golden set, twice.

1. Extractive (Phase 1 pipeline, no judge) — the baseline.
2. Generative (local Qwen2.5-0.5B-Instruct + verification) with the
   LLM-as-judge on every given answer.

Both runs share one retriever and one loaded model. Writes
`benchmarks/results/generative_eval.json` (full results + timing
metadata) and `benchmarks/results/generative_eval.md` (summary
generated from the JSON, not hand-typed).

Usage: python -m scripts.run_generative_eval
Takes ~7 minutes on this VM (1.5 shared CPUs): ~5 s per
generated answer, ~4 s per judge call, 50 questions x 2 runs
(427.3 s measured 18 Nov 2026; latency varies with CPU contention).
Run it detached (nohup ... &) and read the log; it prints one
progress line per question.
"""
import json
import time
from pathlib import Path

from app import generative
from app.config import CHUNKS_FILE
from app.eval import load_golden, run_eval
from app.retrieval import Retriever

RESULTS_DIR = Path(__file__).resolve().parent.parent / "benchmarks" / "results"


def _mean(values: list[float]) -> float | None:
    return round(sum(values) / len(values), 2) if values else None


def _progress(i: int, n: int, qid: str) -> None:
    print(f"[{i}/{n}] {qid}", flush=True)


def main() -> dict:
    t_start = time.monotonic()
    chunks = [json.loads(line) for line in CHUNKS_FILE.read_text().splitlines()
              if line.strip()]
    retriever = Retriever(chunks)
    print(f"chunks: {len(chunks)}  embedder: {retriever.embedder}", flush=True)

    t_load = time.monotonic()
    model, _ = generative.load_model()
    load_s = round(time.monotonic() - t_load, 1)
    print(f"generative model: {generative.MODEL_ID}  loaded: {model is not None}  "
          f"load_s: {load_s}  error: {generative.model_load_error()}", flush=True)
    if model is None:
        raise SystemExit("generative model failed to load; refusing to "
                         "write a generative eval with no generator")

    print("== extractive baseline ==", flush=True)
    t0 = time.monotonic()
    extractive = run_eval(retriever, load_golden())
    extractive_s = round(time.monotonic() - t0, 1)

    print("== generative + judge ==", flush=True)
    t0 = time.monotonic()
    gen = run_eval(retriever, load_golden(), generative=True, judge=True,
                   progress=_progress)
    generative_s = round(time.monotonic() - t0, 1)

    gen_lat = [r["generation_latency_s"] for r in gen["per_question"]
               if "generation_latency_s" in r]
    judge_lat = [r["judge"]["latency_s"] for r in gen["per_question"]
                 if "judge" in r]
    result = {
        "model": generative.MODEL_ID,
        "model_params": generative.MODEL_PARAMS,
        "model_file_bytes": generative.MODEL_FILE_BYTES,
        "model_file_mb": generative.MODEL_FILE_MB,
        "cost_per_query_usd": 0.0,
        "load_s": load_s,
        "extractive_eval_s": extractive_s,
        "generative_eval_s": generative_s,
        "total_s": round(time.monotonic() - t_start, 1),
        "mean_generation_latency_s": _mean(gen_lat),
        "mean_judge_latency_s": _mean(judge_lat),
        "extractive": {k: v for k, v in extractive.items()},
        "generative": {k: v for k, v in gen.items()},
    }
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (RESULTS_DIR / "generative_eval.json").write_text(
        json.dumps(result, indent=2))
    (RESULTS_DIR / "generative_eval.md").write_text(_render_md(result))
    print(json.dumps({k: v for k, v in result.items()
                      if k not in ("extractive", "generative")}, indent=2))
    print("wrote benchmarks/results/generative_eval.json + .md")
    return result


def _render_md(result: dict) -> str:
    ext, gen = result["extractive"], result["generative"]
    lines = [
        "# Generative eval — Qwen2.5-0.5B-Instruct (local, $0)",
        "",
        "Generated by `python -m scripts.run_generative_eval` from the "
        "measured JSON in `generative_eval.json`. Same 50-question golden "
        "set for both columns.",
        "",
        f"Model: {result['model']} ({result['model_params']}, "
        f"{result['model_file_mb']} MB weights, bf16, CPU, greedy). "
        f"Load: {result['load_s']} s. "
        f"Mean generation latency: {result['mean_generation_latency_s']} s. "
        f"Mean judge latency: {result['mean_judge_latency_s']} s. "
        f"Total run: {result['total_s']} s.",
        "",
        "| Metric | Extractive (Phase 1) | Generative (Phase 2 Step 1) |",
        "|---|---|---|",
        f"| recall@3 | {ext['recall@3']} | {gen['recall@3']} |",
        f"| recall@5 | {ext['recall@5']} | {gen['recall@5']} |",
        f"| answer_relevance_proxy | {ext['answer_relevance_proxy']} | {gen['answer_relevance_proxy']} |",
        f"| answer_only_relevance | {ext['answer_only_relevance']} | {gen['answer_only_relevance']} |",
        f"| faithfulness (verbatim proxy) | {ext['faithfulness']} | {gen['faithfulness']} |",
        f"| abstention_accuracy | {ext['abstention_accuracy']} | {gen['abstention_accuracy']} |",
        f"| eligibility_accuracy | {ext['eligibility_accuracy']} | {gen['eligibility_accuracy']} |",
        f"| judge faithfulness | — | {gen.get('judge_faithfulness')} (n={gen.get('judge_n')}, unparsed={gen.get('judge_unparsed')}) |",
        f"| judge relevance | — | {gen.get('judge_relevance')} (n={gen.get('judge_n')}, unparsed={gen.get('judge_unparsed')}) |",
        "",
        f"Generative answer modes (in-corpus n={gen['n_in_corpus']}): "
        f"{gen.get('generative_modes')}.",
        "",
        "## Per-question failures (generative run)",
        "",
    ]
    for row in gen["per_question"]:
        problems = []
        if not row["answer_only_relevant"]:
            problems.append("answer-only miss")
        if row.get("judge") and row["judge"]["parsed"]:
            if row["judge"]["faithfulness"] == 0:
                problems.append("judge: unfaithful")
            if row["judge"]["relevance"] == 0:
                problems.append("judge: irrelevant")
        if row.get("judge") and not row["judge"]["parsed"]:
            problems.append("judge: unparsed")
        if problems:
            lines.append(f"- {row['id']}: {'; '.join(problems)} "
                         f"(mode={row.get('answer_mode')}, "
                         f"found={row['found']}, "
                         f"judge={row.get('judge')})")
    lines.append("")
    lines.append("Note: the verbatim `faithfulness` proxy measures "
                 "substring overlap with cited chunks, which a "
                 "paraphrasing generator fails by design. For generative "
                 "answers the judge faithfulness is the meaningful "
                 "number; the deterministic verification step (every kept "
                 "sentence grounded in a cited chunk) is the guard.")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main()
